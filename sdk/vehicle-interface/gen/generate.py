#!/usr/bin/env python3
"""Generate the vehicle-interface AIDL, enums and callback base classes from SPEC.md.

Usage: python3 sdk/vehicle-interface/gen/generate.py

Reads only SPEC.md. Hand-written Java (not generated): Wire.java and the three
parcelables of SPEC section 7 (BleDetails, IMUData, VehicleRangeBasedOnModes).
The script checks its parse against the totals stated in the spec and stops on mismatch.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "SPEC.md"
AIDL_DIR = ROOT / "aidl" / "com" / "olaelectric" / "vehicleinterface"
JAVA_DIR = ROOT / "java" / "com" / "olaelectric" / "vehicleinterface"

PRIMITIVES = {"boolean", "int", "long", "float", "double", "String"}
HEADER = "Generated by gen/generate.py from SPEC.md. Do not edit by hand."
SERVICES = ["IVehicleService", "IParserService", "ICommanderService"]


def fail(msg):
    sys.exit("generate: " + msg)


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def section(lines, start, end):
    s = next(i for i, l in enumerate(lines) if re.match(start, l))
    e = next(i for i in range(s + 1, len(lines)) if re.match(end, lines[i]))
    return lines[s:e]


def parse_interfaces(lines):
    binders = {}
    for l in section(lines, r"^### 3\.2 ", r"^### 3\.3 "):
        m = re.match(r"^- (\w+) \(code \d+\) returns the (\w+) binder", l)
        if m:
            binders[m.group(1)] = m.group(2)

    ifaces, cur = {}, None
    for line in section(lines, r"^## 5\. ", r"^## 6\. "):
        h = re.match(r"^#{3,4} (?:5\.\d )?(I\w+)$", line)
        if h:
            cur = h.group(1)
            ifaces[cur] = []
            continue
        if not (cur and re.match(r"^\| \d+ \|", line)):
            continue
        c = cells(line)
        code, name, args, reply, mode = int(c[0]), c[1], c[2], c[3], c[-1]
        if code != len(ifaces[cur]) + 1:
            fail(f"{cur}.{name}: code {code} is not sequential")
        ptypes = []
        if args != "none":
            for i, part in enumerate(args.split("<br>"), 1):
                m = re.match(r"^(\d+)\. (\w+): ", part.strip())
                if not m or int(m.group(1)) != i:
                    fail(f"{cur}.{name}: bad argument '{part}'")
                ptypes.append(m.group(2))
        if cur in SERVICES:
            if "then strong binder" in reply:
                ret = binders[name]
            elif "then int (1 = true" in reply:
                ret = "boolean"
            elif "then string" in reply:
                ret = "String"
            elif m2 := re.search(r"then nullable (\w+)", reply):
                ret = m2.group(1)
            else:
                ret = "void"
        else:
            ret = "void"
        ifaces[cur].append({
            "code": code, "name": name, "args": ptypes, "ret": ret,
            "oneway": mode == "oneway",
        })

    # Totals from section 4 (callback method counts) and section 1.
    counts = {}
    for l in section(lines, r"^## 4\. ", r"^## 5\. "):
        if re.match(r"^\| I\w+Callbacks \|", l):
            c = cells(l)
            counts[c[0]] = int(c[-1])
    for name, n in counts.items():
        if len(ifaces.get(name, [])) != n:
            fail(f"{name}: parsed {len(ifaces.get(name, []))} methods, spec says {n}")
    total = sum(len(v) for v in ifaces.values())
    if total != 232:
        fail(f"parsed {total} methods, spec says 232")
    return ifaces


def parse_enums(lines):
    enums, expected, read_map = {}, {}, {}
    cur = None
    for line in section(lines, r"^### 6\.2 ", r"^## 7\. "):
        h = re.match(r"^#### (\w+)$", line)
        if h:
            cur = h.group(1)
            enums[cur] = {}
            continue
        if cur is None:
            continue
        mc = re.search(r"(\d+) constants\.", line)
        if mc:
            expected[cur] = int(mc.group(1))
        if re.match(r"^\| \d+ \|", line):
            c = cells(line)
            for k in range(0, len(c) - 1, 2):
                if c[k].isdigit() and c[k + 1]:
                    enums[cur][int(c[k])] = c[k + 1]

    cur = None
    for line in section(lines, r"^### 6\.1 ", r"^### 6\.2 "):
        h = re.match(r"^### 6\.1 (\w+):", line)
        if h:
            cur = h.group(1)
        elif cur and re.match(r"^\| \d+ \|", line):
            c = cells(line)
            read_map[int(c[0])] = c[1]

    out = {}
    for name, idx in enums.items():
        if sorted(idx) != list(range(len(idx))):
            fail(f"{name}: indexes are not 0..N-1")
        if len(idx) != expected.get(name, -1):
            fail(f"{name}: parsed {len(idx)} constants, spec says {expected.get(name)}")
        consts = [idx[i] for i in range(len(idx))]
        if len(set(consts)) != len(consts):
            fail(f"{name}: duplicate constant names")
        out[name] = consts
    if len(out) != 37 or sum(len(v) for v in out.values()) != 635:
        fail(f"parsed {len(out)} enums / {sum(len(v) for v in out.values())} constants, spec says 37 / 635")
    for v, n in read_map.items():
        if n not in out["ProximityCommandType"]:
            fail(f"6.1 read name {n} is not a ProximityCommandType constant")
    return out, read_map


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def service_aidl(name, methods):
    body, used = [], set()
    for m in methods:
        args = ", ".join(f"in {a} arg{i}" if a not in PRIMITIVES else f"{a} arg{i}"
                         for i, a in enumerate(m["args"]))
        used.update(t for t in m["args"] + [m["ret"]] if t not in PRIMITIVES and t != "void")
        mod = "oneway " if m["oneway"] else ""
        body.append(f"    {mod}{m['ret']} {m['name']}({args});")
    # AIDL resolves even same-package types only through explicit imports.
    imports = "".join(f"import com.olaelectric.vehicleinterface.{t};\n" for t in sorted(used - {name}))
    return (f"// {HEADER}\npackage com.olaelectric.vehicleinterface;\n\n{imports}"
            f"\ninterface {name} {{\n" + "\n".join(body) + "\n}\n")


def enum_java(name, consts, read_map):
    lines = [f"// {HEADER}", "package com.olaelectric.vehicleinterface;", "",
             "import android.os.Parcel;", "import android.os.Parcelable;", "",
             "/** Enumeration on the wire as its int index (SPEC 2.5). */",
             f"public enum {name} implements Parcelable {{"]
    lines.append(",\n".join(f"    {c}" for c in consts) + ";")
    lines.append("")
    if name == "ProximityCommandType":
        lines.append("    /** Index 0 to 64, or one of the extra read values of SPEC 6.1. */")
        lines.append(f"    static {name} fromWire(int value) {{")
        lines.append("        switch (value) {")
        for v in sorted(read_map):
            lines.append(f"            case {v}: return {read_map[v]};")
        lines.append("            default: return Wire.at(values(), value);")
        lines.append("        }")
    else:
        lines.append("    static " + name + " fromWire(int value) {")
        lines.append("        return Wire.at(values(), value);")
    lines.append("    }")
    lines += [
        "",
        f"    public static final Parcelable.Creator<{name}> CREATOR = new Parcelable.Creator<{name}>() {{",
        f"        @Override public {name} createFromParcel(Parcel in) {{",
        "            return fromWire(in.readInt());",
        "        }",
        "",
        f"        @Override public {name}[] newArray(int size) {{",
        f"            return new {name}[size];",
        "        }",
        "    };",
        "",
        "    @Override public int describeContents() {",
        "        return 0;",
        "    }",
        "",
        "    @Override public void writeToParcel(Parcel out, int flags) {",
        "        out.writeInt(ordinal());",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def callback_base(iface, methods):
    base = iface[1:].replace("Callbacks", "CallbacksBase", 1)
    lines = [f"// {HEADER}", "package com.olaelectric.vehicleinterface;", "",
             "import dev.olatool.dash.Trace;", "",
             f"/**",
             f" * {iface} with each call logged through Trace and otherwise a no-op.",
             " * Subclass anonymously and override only the methods that need work.",
             " */",
             f"public class {base} extends {iface}.Stub {{"]
    for m in methods:
        params = ", ".join(f"{a} arg{i}" for i, a in enumerate(m["args"]))
        passed = "".join(f", arg{i}" for i in range(len(m["args"])))
        lines += [
            "    @Override",
            f"    public void {m['name']}({params}) {{",
            f"        Trace.call(\"{iface}.{m['name']}\"{passed});",
            "    }",
            "",
        ]
    lines[-1:] = ["}"]
    return base, "\n".join(lines) + "\n"


def main():
    lines = SPEC.read_text(encoding="utf-8").splitlines()
    ifaces = parse_interfaces(lines)
    enums, read_map = parse_enums(lines)

    for name, methods in ifaces.items():
        write(AIDL_DIR / f"{name}.aidl", service_aidl(name, methods))
    for name, consts in enums.items():
        write(AIDL_DIR / f"{name}.aidl", f"package com.olaelectric.vehicleinterface;\n\nparcelable {name};\n")
        write(JAVA_DIR / f"{name}.java", enum_java(name, consts, read_map if name == "ProximityCommandType" else {}))
    for name in ["BleDetails", "IMUData", "VehicleRangeBasedOnModes"]:
        write(AIDL_DIR / f"{name}.aidl", f"package com.olaelectric.vehicleinterface;\n\nparcelable {name};\n")

    bases = []
    for name, methods in ifaces.items():
        if name in SERVICES:
            continue
        base, text = callback_base(name, methods)
        bases.append(base)
        write(JAVA_DIR / f"{base}.java", text)
        write(AIDL_DIR / f"{name}.aidl", service_aidl(name, methods))

    print(f"interfaces: {len(ifaces)} ({len(bases)} callback bases), "
          f"methods: {sum(len(v) for v in ifaces.values())}, "
          f"enums: {len(enums)}, constants: {sum(len(v) for v in enums.values())}")


if __name__ == "__main__":
    main()
